#!/usr/bin/env python3
"""Generates crates/parley-core/src/ebcdic/tables.rs from the system's iconv (glibc) code pages.

Only bytes X'40' to X'FF' are tabled: below X'40' the 5250 data stream has orders, attributes and
controls, never displayable characters. Control characters in the range (X'FF' is EO) map to a space.

Run `python3 scripts/gen-ebcdic.py` after adding a code page, then `cargo fmt`, and commit the result.
"""

import subprocess
import sys
from pathlib import Path

# (Rust constant, iconv name, description)
CODE_PAGES = [
    ("CCSID_37", "IBM037", "CCSID 37: USA, Canada, Netherlands, Portugal, Brazil, Australia, New Zealand"),
    ("CCSID_277", "IBM277", "CCSID 277: Denmark, Norway"),
    ("CCSID_1140", "IBM1140", "CCSID 1140: CCSID 37 with the euro sign"),
    ("CCSID_1142", "IBM1142", "CCSID 1142: CCSID 277 with the euro sign"),
]
OUT = Path(__file__).resolve().parent.parent / "crates" / "parley-core" / "src" / "ebcdic" / "tables.rs"


def table(iconv_name: str) -> list[str]:
    raw = bytes(range(0x40, 0x100))
    utf32 = subprocess.run(
        ["iconv", "-f", iconv_name, "-t", "UTF-32BE"], input=raw, capture_output=True, check=True
    ).stdout
    chars = [chr(int.from_bytes(utf32[i : i + 4], "big")) for i in range(0, len(utf32), 4)]
    if len(chars) != len(raw):
        sys.exit(f"{iconv_name}: expected {len(raw)} characters, got {len(chars)}")
    return [" " if (ord(c) < 0x20 or 0x7F <= ord(c) < 0xA0) else c for c in chars]


def rust_char(c: str) -> str:
    if c in ("'", "\\"):
        return f"'\\{c}'"
    if ord(c) > 0x7E:
        return f"'\\u{{{ord(c):04x}}}'"
    return f"'{c}'"


def main() -> int:
    lines = [
        "//! Generated by `scripts/gen-ebcdic.py` from iconv: do not edit by hand.",
        "//! Each table maps EBCDIC bytes X'40'..=X'FF' (index = byte - X'40') to Unicode.",
        "",
    ]
    for const, iconv_name, description in CODE_PAGES:
        chars = table(iconv_name)
        lines.append(f"/// {description}.")
        lines.append(f"pub(super) const {const}: [char; 192] = [")
        for row in range(0, 192, 8):
            lines.append("    " + ", ".join(rust_char(c) for c in chars[row : row + 8]) + ",")
        lines.append("];")
        lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"Wrote {len(CODE_PAGES)} code pages to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
